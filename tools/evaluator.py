"""
Evaluation utilities for trained EV charging agents.

This module runs deterministic evaluation episodes outside the training loop.
It uses the held-out demand split, disables exploration noise, and writes
aggregate performance summaries. Detailed traces and PNG plots are collected
only when `enable_png=True`, so training-time interim tests can stay light.

Inputs:
- `test(agent, ...)` receives a trained agent object that exposes
  `set_test_mode()`, `episode_start()`, `episode_end()`, `update_active_evs()`,
  and `act()`.
- Demand episodes are loaded from `environment.readcsv.load_multiple_demand_files`
  using the test split unless `dataset_dir` is provided.
- EV arrivals and EV profiles are generated by `EVEnv`, using the same
  environment configuration as training.

Outputs:
- The returned `test_results` dictionary stores averaged rewards, per-episode
  traces, and performance metrics such as SoC miss rate, average SoC deficit,
  surplus absorption, and supply cooperation.
- When `save_test_detail_files=True`, lightweight CSV/history artifacts are
  saved in `results/TEST{test_episode_num}`. If `enable_png=True`, detailed
  CSV/plot artifacts are also generated there. The root-level
  `test_performance_metrics.*` and `test_episode_rewards_all.*` history files
  are controlled separately by `enable_history_png`. The root
  `results/test_history.json` is always updated so checkpoint-level test curves
  can be regenerated later.

Determinism:
- Evaluation temporarily seeds Python, NumPy, Torch, and CUDA RNGs with
  `ENV_SEED`, then restores the caller's RNG state before returning. This keeps
  checkpoint tests reproducible without perturbing subsequent training samples.
"""

