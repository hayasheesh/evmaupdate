def set_env_seed (seed =None ):
    if seed is not None :
        random .seed (seed )
        np .random .seed (seed )
        torch .manual_seed (seed )
        if torch .cuda .is_available ():
            torch .cuda .manual_seed_all (seed )


def _capture_rng_state ():
    """Snapshot global RNG state across random / numpy / torch (+ cuda)."""
    return {
    'py':random .getstate (),
    'np':np .random .get_state (),
    'torch':torch .get_rng_state (),
    'cuda':(torch .cuda .get_rng_state_all ()
    if torch .cuda .is_available ()else None ),
    }


def _restore_rng_state (state ):
    """Restore RNG state captured by `_capture_rng_state`."""
    if state is None :
        return
    try :
        random .setstate (state ['py'])
        np .random .set_state (state ['np'])
        torch .set_rng_state (state ['torch'])
        if state .get ('cuda')is not None and torch .cuda .is_available ():
            torch .cuda .set_rng_state_all (state ['cuda'])
    except Exception as exc :
        warnings .warn (f"Failed to restore evaluation RNG state: {exc}")


def _evaluation_episode_index (ep_idx ):
    """Return the stable zero-based scenario index for one evaluation rollout."""
    return max (0 ,int (ep_idx )-1 )


def _candidate_bid_bank_dirs (working_dir ):
    """Bank directories that might hold the bid for the episode being plotted.

    The EnvConfig constant is only the default bank. A run launched with
    --bank-dir/--test-bank-dir uses a different one and never writes it back
    into EnvConfig, so consulting the constant alone finds a bid for the right
    date from the wrong bank, the tolerance check below rejects it, and the
    plot silently loses its envelope. The run's own resume manifest records
    the banks it was actually given, so read that first.
    """

    candidates =[]

    def _add (value ):
        if not value :
            return
        text =str (value )
        if text not in candidates :
            candidates .append (text )

    if working_dir :
        manifest =os .path .join (str (working_dir ),"resume","latest.json")
        try :
            with open (manifest ,encoding ="utf-8")as handle :
                context =(json .load (handle )or {}).get ("context")or {}
            _add ((context .get ("test_bid_bank")or {}).get ("path"))
            _add ((context .get ("train_bid_bank")or {}).get ("path"))
        except Exception :
            pass

    try :
        from EnvConfig import (
        LOWER_TRAIN_UPPER_BID_TEST_BANK_DIR ,
        LOWER_TRAIN_UPPER_BID_BANK_DIR ,
        )
        _add (LOWER_TRAIN_UPPER_BID_TEST_BANK_DIR )
        _add (LOWER_TRAIN_UPPER_BID_BANK_DIR )
    except Exception :
        pass

    # A run that has not written its first resume manifest yet, and whose
    # banks are not the EnvConfig defaults, is otherwise unreachable. Its bank
    # still sits beside the ones above, so offer those as a last resort. The
    # tolerance check decides which one is right, so a wider list costs a few
    # rejected reads and cannot produce a wrong envelope.
    for known in list (candidates ):
        parent =os .path .dirname (str (known ))
        if not parent or not os .path .isdir (parent ):
            continue
        for name in sorted (os .listdir (parent )):
            sibling =os .path .join (parent ,name )
            if os .path .isdir (sibling ):
                _add (sibling )

    return candidates


def _bid_envelope_for_env (local_env ,service_date ,working_dir =None ):
    """Per-step baseline and bid envelope for the episode the env was reset to.

    Each candidate bank is looked up by date and then checked against the
    tolerance series the environment actually holds: for the right bid the
    implied band -- frac*up or frac*down while an instruction is running,
    frac*(up+down) while it is not -- reproduces that series step for step.
    The first candidate that reproduces it wins; one that fails is skipped,
    so a plot never shows a baseline belonging to a different day or a
    different bank rather than silently mislabelling one. Widening the search
    cannot loosen that: the check is what decides, not the order.
    """

    try :
        from training .bid_bank import BidBank
        from market .bid_env import STEPS_PER_BLOCK
    except Exception :
        return None

    target =getattr (local_env ,"net_demand_series_cpu",None )
    tol =getattr (local_env ,"_tol_narrow_series",None )
    if target is None or tol is None :
        return None
    target =np .asarray (target ,dtype =float ).reshape (-1 )
    tol =np .asarray (tol ,dtype =float ).reshape (-1 )
    steps =min (target .size ,tol .size )
    if steps ==0 :
        return None

    block =np .arange (steps )//STEPS_PER_BLOCK

    for bank_dir in _candidate_bid_bank_dirs (working_dir ):
        try :
            fixed_bid =BidBank (bank_dir ).load_date (str (service_date ))
            baseline =np .asarray (fixed_bid ["baseline_plan"],dtype =float )
            up =np .asarray (fixed_bid ["up_plan"],dtype =float )
            down =np .asarray (fixed_bid ["down_plan"],dtype =float )
            frac =float (fixed_bid .get ("assessment_band_fraction")or 0.1 )
        except Exception :
            continue

        if block .max (initial =0 )>=baseline .size :
            continue
        baseline_by_step =baseline [block ]
        up_by_step =up [block ]
        down_by_step =down [block ]

        # The target series is stored float32, so an idle step lands within a
        # few ULPs of the float64 baseline rather than exactly on it. At 1e3 kW
        # that gap is ~1e-4, which a fixed 1e-6 test reads as a live
        # instruction. Scale the deadzone with the magnitude involved; 1 mW is
        # physically nothing.
        regulation =target [:steps ]-baseline_by_step
        idle_eps =np .maximum (1e-3 ,1e-6 *np .abs (baseline_by_step ))
        expected =np .where (
        regulation <-idle_eps ,frac *up_by_step ,
        np .where (regulation >idle_eps ,frac *down_by_step ,frac *(up_by_step +down_by_step )),
        )
        expected =np .maximum (expected ,1e-6 )
        if not np .allclose (expected ,tol [:steps ],atol =1e-3 ,rtol =1e-4 ):
            continue

        return {
        "baseline":baseline_by_step ,
        "lower":baseline_by_step -up_by_step ,
        "upper":baseline_by_step +down_by_step ,
        }

    return None


def _summarize_test_results (test_results ):
    pm =test_results .get ('performance_metrics',{})if test_results else {}

    def _mean (values ,default =0.0 ):
        if not values :
            return default
        arr =np .asarray (values ,dtype =np .float64 )
        if arr .size ==0 :
            return default
        return float (np .mean (arr ))

    def _sum_int (values ):
        if not values :
            return 0
        return int (np .sum (np .asarray (values ,dtype =np .float64 )))

    local_reward =_mean (test_results .get ('all_local_rewards',[])if test_results else [])
    global_reward =_mean (test_results .get ('all_global_rewards',[])if test_results else [])
    soc_miss =_mean (pm .get ('soc_miss_count',[]))
    soc_hit =100.0 -soc_miss
    central_soc_miss =_mean (pm .get ('central_soc_miss_count',[]))
    central_soc_hit =100.0 -central_soc_miss
    avg_soc_deficit =_mean (pm .get ('avg_soc_deficit',[]))
    surplus_steps =_sum_int (pm .get ('surplus_steps',[]))
    surplus_within =_sum_int (pm .get ('surplus_within_narrow',[]))
    shortage_steps =_sum_int (pm .get ('shortage_steps',[]))
    shortage_within =_sum_int (pm .get ('shortage_within_narrow',[]))
    zero_steps =_sum_int (pm .get ('zero_request_steps',[]))
    zero_within =_sum_int (pm .get ('zero_request_within_narrow',[]))
    dispatch_steps =surplus_steps +shortage_steps +zero_steps
    dispatch_within =surplus_within +shortage_within +zero_within
    dispatch_rate =(dispatch_within /dispatch_steps *100.0 )if dispatch_steps >0 else 0.0
    system_surplus_steps =_sum_int (pm .get ('system_surplus_steps',[]))
    system_surplus_within =_sum_int (pm .get ('system_surplus_within_narrow',[]))
    system_shortage_steps =_sum_int (pm .get ('system_shortage_steps',[]))
    system_shortage_within =_sum_int (pm .get ('system_shortage_within_narrow',[]))
    system_zero_steps =_sum_int (pm .get ('system_zero_request_steps',[]))
    system_zero_within =_sum_int (pm .get ('system_zero_request_within_narrow',[]))
    system_dispatch_steps =system_surplus_steps +system_shortage_steps +system_zero_steps
    system_dispatch_within =system_surplus_within +system_shortage_within +system_zero_within
    system_dispatch_rate =(
    system_dispatch_within /system_dispatch_steps *100.0
    if system_dispatch_steps >0 else 0.0
    )
    central_surplus_steps =_sum_int (pm .get ('central_surplus_steps',[]))
    central_surplus_within =_sum_int (pm .get ('central_surplus_within_narrow',[]))
    central_shortage_steps =_sum_int (pm .get ('central_shortage_steps',[]))
    central_shortage_within =_sum_int (pm .get ('central_shortage_within_narrow',[]))
    central_zero_steps =_sum_int (pm .get ('central_zero_request_steps',[]))
    central_zero_within =_sum_int (pm .get ('central_zero_request_within_narrow',[]))
    central_dispatch_steps =central_surplus_steps +central_shortage_steps +central_zero_steps
    central_dispatch_within =central_surplus_within +central_shortage_within +central_zero_within
    central_dispatch_rate =(
    central_dispatch_within /central_dispatch_steps *100.0
    if central_dispatch_steps >0 else 0.0
    )
    surplus_rate =(surplus_within /surplus_steps *100.0 )if surplus_steps >0 else 0.0
    supply_rate =(shortage_within /shortage_steps *100.0 )if shortage_steps >0 else 0.0
    departing_evs =_sum_int (pm .get ('departing_evs',[]))
    departing_evs_soc_met =_sum_int (pm .get ('departing_evs_soc_met',[]))
    central_departing_evs_soc_met =_sum_int (pm .get ('central_departing_evs_soc_met',[]))
    num_episodes =len (test_results .get ('all_rewards',[])if test_results else [])
    return {
    'num_episodes':num_episodes ,
    'local_reward':local_reward ,
    'global_reward':global_reward ,
    'soc_hit':soc_hit ,
    'central_soc_hit':central_soc_hit ,
    'avg_soc_deficit':avg_soc_deficit ,
    'dispatch_rate':dispatch_rate ,
    'system_dispatch_rate':system_dispatch_rate ,
    'central_dispatch_rate':central_dispatch_rate ,
    'raw_actor_mae_kw':_mean (pm .get ('raw_actor_mae_kw',[])),
    'pre_bess_mae_kw':_mean (pm .get ('pre_bess_mae_kw',[])),
    'post_bess_mae_kw':_mean (pm .get ('post_bess_mae_kw',[])),
    'bess_final_soc_pct':_mean (pm .get ('bess_final_soc_pct',[])),
    'bess_max_abs_power_kw':max (pm .get ('bess_max_abs_power_kw',[])or [0.0 ]),
    'bess_throughput_kwh':_mean (pm .get ('bess_throughput_kwh',[])),
    'surplus_rate':surplus_rate ,
    'supply_rate':supply_rate ,
    'departing_evs':departing_evs ,
    'departing_evs_soc_met':departing_evs_soc_met ,
    'central_departing_evs_soc_met':central_departing_evs_soc_met ,
    'surplus_steps':surplus_steps ,
    'surplus_within':surplus_within ,
    'shortage_steps':shortage_steps ,
    'shortage_within':shortage_within ,
    'dispatch_steps':dispatch_steps ,
    'dispatch_within':dispatch_within ,
    'system_dispatch_steps':system_dispatch_steps ,
    'system_dispatch_within':system_dispatch_within ,
    'central_dispatch_steps':central_dispatch_steps ,
    'central_dispatch_within':central_dispatch_within ,
    }


def _print_test_summary (test_results ,test_episode_num =None ,duration_sec =None ):
    summary =_summarize_test_results (test_results )
    label ="TEST" if test_episode_num is None else f"TEST{test_episode_num}"
    duration_part ="" if duration_sec is None else f" | duration={duration_sec:.1f}s"
    # With the battery off the system column is the central column and the third
    # MAE is the second, so both would print the same number twice.
    if bool (TRAIN_USE_RESIDUAL_BESS ):
        _rates =(
        f"MARL/Central/System={summary['dispatch_rate']:.2f}/"
        f"{summary['central_dispatch_rate']:.2f}/{summary['system_dispatch_rate']:.2f}%"
        )
        _mae =(
        f"MAE={summary['raw_actor_mae_kw']:.1f}->"
        f"{summary['pre_bess_mae_kw']:.1f}->{summary['post_bess_mae_kw']:.1f}kW"
        )
        _bess =(
        f" | BESS max={summary['bess_max_abs_power_kw']:.1f}kW"
        f", SoC={summary['bess_final_soc_pct']:.1f}%"
        )
    else :
        _rates =(
        f"MARL/Central={summary['dispatch_rate']:.2f}/"
        f"{summary['central_dispatch_rate']:.2f}%"
        )
        _mae =(
        f"MAE={summary['raw_actor_mae_kw']:.1f}->"
        f"{summary['pre_bess_mae_kw']:.1f}kW"
        )
        _bess =""
    print (
    f"[{label} summary] episodes={summary['num_episodes']}"
    f" | local={summary['local_reward']:.4f}"
    f" | global={summary['global_reward']:.4f}"
    f" | SoC actor/physical={summary['soc_hit']:.2f}/"
    f"{summary['central_soc_hit']:.2f}%"
    f" ({summary['departing_evs_soc_met']}/"
    f"{summary['central_departing_evs_soc_met']}/"
    f"{summary['departing_evs']} EV)"
    f" | deficit={summary['avg_soc_deficit']:.2f}kWh"
    f" | {_rates}"
    f" | {_mae}"
    f"{_bess}"
    # Not a battery figure: the numerator and denominator of the MARL column.
    f" ({summary['dispatch_within']}/{summary['dispatch_steps']} MARL steps)"
    f" | surplus={summary['surplus_rate']:.2f}%"
    f" | supply={summary['supply_rate']:.2f}%"
    f"{duration_part}"
    )


def _episode_payload_to_series_and_date (payload ,episode_steps ):
    service_date =None
    if isinstance (payload ,dict ):
        service_date =payload .get ("date")
        payload =payload .get ("series")
    data =np .asarray (payload ,dtype =float ).reshape (-1 )
    if data .size ==0 :
        raise ValueError ("Demand episode is empty.")
    if data .size >=int (episode_steps ):
        return data [:int (episode_steps )],service_date
    return np .pad (data ,(0 ,int (episode_steps )-int (data .size ))),service_date


def _reset_env_with_day_context (
env ,
episode_demand ,
service_date ,
arrival_sampler ,
tol_narrow_series =None ,
arrival_probabilities_by_station =None ,
day_context =None ,
market_context_series =None ,
):
    kwargs ={"net_demand_series":episode_demand ,"service_date":service_date }
    if tol_narrow_series is not None :
        kwargs ["tol_narrow_series"]=tol_narrow_series
    if market_context_series is not None :
        kwargs ["market_context_series"]=market_context_series
    if arrival_probabilities_by_station is not None :
        kwargs ["arrival_probabilities_by_station"]=arrival_probabilities_by_station
        if day_context is not None :
            kwargs ["day_context"]=day_context
    elif arrival_sampler is not None :
        scenario =arrival_sampler .scenario_for_day (service_date )
        kwargs ["arrival_probabilities_by_station"]=scenario .arrival_probabilities_by_station
        kwargs ["day_context"]=scenario .day_context
    return env .reset (**kwargs )




